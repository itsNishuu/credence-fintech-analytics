"""Load the CSV star schema into SQLite, build the views, run every query and save the results.

Run:  python3 analytics/run_sql.py           (writes analytics/output/*.csv and analytics/output/RESULTS.md)
"""
from __future__ import annotations

import csv
import sqlite3
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA, SQL, OUT = HERE / 'data', HERE / 'sql', HERE / 'output'
LOAD_ORDER = ['dim_branch', 'dim_grade', 'dim_date', 'dim_borrower', 'dim_loan', 'fact_loan_month', 'fact_financials_quarter']


def build(db_path: str | Path = ':memory:') -> sqlite3.Connection:
    con = sqlite3.connect(db_path)
    con.execute('PRAGMA foreign_keys = ON')
    con.executescript((SQL / 'schema.sql').read_text())
    for table in LOAD_ORDER:
        with open(DATA / f'{table}.csv', newline='', encoding='utf-8') as f:
            rows = list(csv.reader(f))
        header, body = rows[0], rows[1:]
        body = [[None if v == '' else v for v in r] for r in body]
        con.executemany(f'INSERT INTO {table} ({", ".join(header)}) VALUES ({", ".join("?" * len(header))})', body)
    con.commit()
    con.executescript((SQL / 'views.sql').read_text())
    return con


def queries():
    return sorted((SQL / 'queries').glob('*.sql'))


def run(con: sqlite3.Connection, path: Path):
    t0 = time.perf_counter()
    cur = con.execute(path.read_text())
    cols = [d[0] for d in cur.description]
    rows = cur.fetchall()
    return cols, rows, (time.perf_counter() - t0) * 1000


def question(path: Path) -> str:
    first = path.read_text().splitlines()[0]
    return first.removeprefix('-- Q:').strip()


def main():
    t0 = time.perf_counter()
    con = build()
    load_ms = (time.perf_counter() - t0) * 1000
    OUT.mkdir(exist_ok=True)
    counts = {t: con.execute(f'SELECT COUNT(*) FROM {t}').fetchone()[0] for t in LOAD_ORDER}
    lines = ['# Credence SQL results', '',
             'Generated by `python3 analytics/run_sql.py` on the fictional loan book (Rs lakh). Do not edit by hand.', '',
             f'Loaded {sum(counts.values()):,} rows into SQLite: ' + ', '.join(f'`{k}` {v:,}' for k, v in counts.items()) + '.', '']
    for path in queries():
        cols, rows, ms = run(con, path)
        with open(OUT / f'{path.stem}.csv', 'w', newline='', encoding='utf-8') as f:
            w = csv.writer(f, lineterminator='\n')
            w.writerow(cols)
            w.writerows(rows)
        lines += [f'## {path.stem.replace("_", " ", 1)}', '', f'**{question(path)}**  ',
                  f'[`sql/queries/{path.name}`](../sql/queries/{path.name}) · {len(rows)} rows', '']
        show = rows[:12]
        lines += ['| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)]
        lines += ['| ' + ' | '.join('' if v is None else f'{v:,}' if isinstance(v, (int, float)) and not isinstance(v, bool) else str(v) for v in r) + ' |' for r in show]
        if len(rows) > len(show):
            lines.append(f'\n_First {len(show)} of {len(rows)} rows; full result in `output/{path.stem}.csv`._')
        lines.append('')
        print(f'{path.stem:<28} {len(rows):>4} rows {ms:7.1f} ms')
    print(f'loaded {sum(counts.values()):,} rows in {load_ms:.0f} ms')
    (OUT / 'RESULTS.md').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
